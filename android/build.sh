#!/bin/bash
# Builds Auto Apply without Gradle.
#
#   ./build.sh               -> out/github/AutoApply.apk  APK that updates itself from GitHub releases
#   FLAVOR=play ./build.sh   -> out/play/AutoApply.aab    bundle for Google Play (no self-update), signed with the upload key
#
#   SERVER_URL=https://autoapply.example.com  builds the server in (without it the app asks for the server address)
#   VERSION_CODE=7 VERSION_NAME=2.1           override the manifest's version
#
# Needs: JDK 17+, aapt, aapt2, dalvik-exchange (dx), zipalign, apksigner, jarsigner, android-34.jar, bundletool.jar.
set -euo pipefail
cd "$(dirname "$0")"
unset JAVA_TOOL_OPTIONS
FLAVOR=${FLAVOR:-github}
SERVER_URL=${SERVER_URL:-}
ANDROID_JAR=${ANDROID_JAR:-/home/claude/android-tools/android-34.jar}
BUNDLETOOL=${BUNDLETOOL:-/home/claude/android-tools/bundletool/bundletool.jar}
KS=${KEYSTORE:-keystore/autoapply.jks}
KS_PASS=${KS_PASS:-autoapply}
OUT=out/$FLAVOR

case "$FLAVOR" in github|play) ;; *) echo "FLAVOR must be github or play" >&2; exit 1 ;; esac
SERVER_URL=${SERVER_URL%/}
if [ -n "$SERVER_URL" ] && ! [[ "$SERVER_URL" =~ ^https://[A-Za-z0-9.-]+(:[0-9]+)?$ ]]; then
  echo "SERVER_URL must look like https://autoapply.example.com" >&2; exit 1
fi
if [ ! -f "$KS" ]; then
  if [ -n "${CI:-}" ]; then
    echo "No keystore at $KS. Add the KEYSTORE_BASE64 secret (a new key could not update installed apps)." >&2; exit 1
  fi
  keytool -genkeypair -keystore "$KS" -storepass "$KS_PASS" -keypass "$KS_PASS" -alias autoapply \
    -keyalg RSA -keysize 2048 -validity 20000 -dname "CN=Auto Apply, O=Personal" >/dev/null 2>&1
fi

rm -rf "$OUT" && mkdir -p "$OUT/gen/com/autoapply/bot/app" "$OUT/classes"

# The manifest for this flavor: the Play build leaves out the self-update parts.
if [ "$FLAVOR" = play ]; then
  sed '/<!-- github:start/,/<!-- github:end -->/d' AndroidManifest.xml > "$OUT/AndroidManifest.xml"
else
  cp AndroidManifest.xml "$OUT/AndroidManifest.xml"
fi
[ -n "${VERSION_CODE:-}" ] && sed -i "s/android:versionCode=\"[0-9]*\"/android:versionCode=\"$VERSION_CODE\"/" "$OUT/AndroidManifest.xml"
[ -n "${VERSION_NAME:-}" ] && sed -i "s/android:versionName=\"[^\"]*\"/android:versionName=\"$VERSION_NAME\"/" "$OUT/AndroidManifest.xml"

cat > "$OUT/gen/com/autoapply/bot/app/BuildConfig.java" <<JAVA
package com.autoapply.bot.app;

/** Generated by build.sh. */
public final class BuildConfig {
    public static final String FLAVOR = "$FLAVOR";
    public static final String SERVER_URL = "$SERVER_URL";

    private BuildConfig() {
    }
}
JAVA

compile_java() {
  javac --release 8 -Xlint:-options -nowarn -encoding UTF-8 -classpath "$ANDROID_JAR" -d "$OUT/classes" \
    $(find src "flavors/$FLAVOR" "$OUT/gen" -name "*.java")
  dalvik-exchange --dex --min-sdk-version=24 --output="$OUT/classes.dex" "$OUT/classes"
}

if [ "$FLAVOR" = github ]; then
  aapt package -f -m -J "$OUT/gen" -M "$OUT/AndroidManifest.xml" -S res -I "$ANDROID_JAR"
  compile_java
  aapt package -f -M "$OUT/AndroidManifest.xml" -S res -A assets -I "$ANDROID_JAR" -F "$OUT/unsigned.apk"
  (cd "$OUT" && aapt add unsigned.apk classes.dex >/dev/null)
  zipalign -f -p 4 "$OUT/unsigned.apk" "$OUT/aligned.apk"
  apksigner sign --ks "$KS" --ks-pass "pass:$KS_PASS" --key-pass "pass:$KS_PASS" --ks-key-alias autoapply \
    --out "$OUT/AutoApply.apk" "$OUT/aligned.apk"
  apksigner verify "$OUT/AutoApply.apk"
  ls -la "$OUT/AutoApply.apk"
  exit 0
fi

# ---- Google Play: an Android App Bundle (resources in protobuf format from aapt2, assembled by bundletool)
aapt2 compile --dir res -o "$OUT/res.zip"
aapt2 link --proto-format -o "$OUT/base-proto.apk" -I "$ANDROID_JAR" --manifest "$OUT/AndroidManifest.xml" \
  -A assets --java "$OUT/gen" --auto-add-overlay "$OUT/res.zip"
compile_java
mkdir -p "$OUT/module"
(cd "$OUT/module" && unzip -q ../base-proto.apk && mkdir -p manifest dex && mv AndroidManifest.xml manifest/ \
  && cp ../classes.dex dex/ && zip -q -r -X ../base.zip .)
java -jar "$BUNDLETOOL" build-bundle --modules="$OUT/base.zip" --output="$OUT/AutoApply.aab"
# Signed with the upload key (Play re-signs the APKs it delivers with the app signing key).
jarsigner -keystore "$KS" -storepass "$KS_PASS" -keypass "$KS_PASS" -sigalg SHA256withRSA -digestalg SHA-256 \
  "$OUT/AutoApply.aab" autoapply >/dev/null
jarsigner -verify "$OUT/AutoApply.aab" | tail -1
ls -la "$OUT/AutoApply.aab"
